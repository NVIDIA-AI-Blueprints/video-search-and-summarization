def sample_bbox_v1(config_path, df):
    """ Bbox sampling method v1 by hugo
        This is legacy method, but we keep this for now. This method could be
        removed in the future.
    
    Args:
        config_path(str): configuration file path
        df(pd.DataFrame): DataFrame containing bounding boxes and metadata
    
    Returns:
        bboxes(list): list of sampled bounding boxes
    """
    bb_cfg = get_config_data(config_path)
    #subregion_dim =bb_cfg.region_split_width, bb_cfg.region_split_height
    subregion_dim = (9, 9) # values came from the legacy config file
    image_dim = bb_cfg.img_width, bb_cfg.img_height

    bboxes = []
    for idx, row in df.iterrows():
        x1 = int(row['x1'])
        x2 = int(row['x2'])
        y1 = int(row['y1'])
        y2 = int(row['y2'])
        bboxes.append((x1, y1, x2, y2))
    bboxes = remove_bbox_touching_borders(bboxes, 15, image_dim)
    if not bboxes:
        print('empty bboxes')

    bboxes.sort(key=functools.cmp_to_key(compare_size))
    bboxes = extract_bbox_from_NxN_regions(bboxes, subregion_dim, image_dim, 
                                            method='legacy')

    return bboxes

def sample_bboxes_v2(config_path, df, output_path):
    """ Box sampling method v2 by dyoo
        This is a new method that uses curve fitting and center based association
        
    Args:
        config_path(str): configuration file path
        df(pd.DataFrame): DataFrame containing bounding boxes and metadata
        output_path(str): path to debug files
    
    Returns:
        bbox_final(list): list of sampled bboxes after grid filter
        bboxes(list): list of sampled bboxes before grid filter 
        bbox_augment(list): list of bboxes generated by box augmentation
    """
    bb_cfg = get_config_data(config_path)
    image_dim = bb_cfg.img_width, bb_cfg.img_height
    subregion_dim =bb_cfg.region_split_width, bb_cfg.region_split_height

    # 1. filtering with confidence score
    df_filtered = df[df['confidence'] > bb_cfg.sampling_confidence] 

    # 2. grid filter to remove bias to repeat bboxes
    bboxes = []
    for idx, row in df_filtered.iterrows():
        x1 = int(row['x1'])
        x2 = int(row['x2'])
        y1 = int(row['y1'])
        y2 = int(row['y2'])
        bboxes.append((x1, y1, x2, y2))
    bboxes = remove_bbox_touching_borders(bboxes, 5, image_dim)
    if not bboxes:
        print('empty bboxes')

    bboxes.sort(key=functools.cmp_to_key(compare_size))
    bboxes = extract_bbox_from_NxN_regions(bboxes, (80, 80), image_dim, 
                                            method='center')

    # convert bboxes to data frame
    df_new = pd.DataFrame(bboxes, columns=['x1', 'y1', 'x2', 'y2'])
    df_new['cx'] = (df_new['x1'] + df_new['x2']) // 2
    df_new['cy'] = (df_new['y1'] + df_new['y2']) // 2
    df_new['width'] = df_new['x2'] - df_new['x1']
    df_new['height'] = df_new['y2'] - df_new['y1']
    df_new['aspect_ratio'] = df_new['width'] / df_new['height']

    # 3. remove boxes close to the boundary
    width = image_dim[0]
    height = image_dim[1]
    x_cutoff = width * 0.05  
    y_cutoff = height * 0.05  
    df_filtered = df_new[(df_new['x1'] > x_cutoff) &
                     (df_new['x2'] < width - x_cutoff) &
                     (df_new['y1'] > y_cutoff) &
                     (df_new['y2'] < height - y_cutoff)]

    # 4. aspect ratio filter
    df_filtered = filter_aspect_ratio(df_filtered, 
                                      bb_cfg,
                                      f'{output_path}/aspect_ratio_filter.png')
    # 5. width filter
    df_filtered, width_popt = filter_width(df_filtered, 
                                           bb_cfg,
                                           f'{output_path}/width_filter.png')
    # 6. height filter
    df_filtered, height_popt = filter_height(df_filtered, 
                                             bb_cfg,
                                             f'{output_path}/height_filter.png')
    df_final = df_filtered

    # convert df to bboxes
    bboxes = []
    for idx, row in df_final.iterrows():
        x1 = int(row['x1'])
        x2 = int(row['x2'])
        y1 = int(row['y1'])
        y2 = int(row['y2'])
        bboxes.append((x1, y1, x2, y2))
    bboxes = remove_bbox_touching_borders(bboxes, 5, image_dim)
    if not bboxes:
        print('empty bboxes')

    bboxes.sort(key=functools.cmp_to_key(compare_size))
    bbox_final = extract_bbox_from_NxN_regions(bboxes, subregion_dim, 
                                                  image_dim, method='center')

    bbox_augment = augmentation(image_dim, subregion_dim, bbox_final, width_popt, height_popt)
    return bbox_final, bboxes, bbox_augment


def find_empty_regions(image_dim, subregion_dim, bbox_sample):
    """ Find if regions in the grid have bounding boxes
    
    Args:
        image_dim(tuple): image dimensions (width, height)
        subregion_dim(tuple): subregion dimensions (width, height)
        bbox_sample(list): list of sampled bounding boxes
    
    Returns:
        filled_regions(np.array): a boolean array indicating if regions are filled or not
    """
    cols = subregion_dim[0]
    rows = subregion_dim[1]
    region_width = image_dim[0] // cols
    region_height = image_dim[1] // rows

    filled_regions = np.zeros(subregion_dim, dtype=bool)
    for bbox in bbox_sample:
        cx = (bbox[0] + bbox[2]) // 2
        cy = (bbox[1] + bbox[3]) // 2
        region_x = cx // region_width
        region_y = cy // region_height
        filled_regions[region_x, region_y] = True
    return filled_regions


def augmentation(image_dim, region_dim, sampled_bboxes, width_popt, height_popt): 
    bbox_gt_augmented = []
    region_split_width = region_dim[0] 
    region_split_height = region_dim[1] 
    cols = region_split_width
    rows = region_split_height
    region_width = image_dim[0] // cols
    region_height = image_dim[1] // rows

    filled_regions = find_empty_regions(image_dim, region_dim, sampled_bboxes)

    bbox_gt_augmented = sampled_bboxes.copy()
    for i in range(region_split_width):
        for j in range(region_split_height):
            if filled_regions[i, j]:
                continue
            cx = i * region_width + region_width // 2
            cy = j * region_height + region_height // 2
            width_pred = func((cx, cy), *width_popt)
            height_pred = func((cx, cy), *height_popt)
            x1 = int(cx - width_pred//2)
            x2 = int(cx + width_pred//2)
            y1 = int(cy - height_pred//2)
            y2 = int(cy + height_pred//2)
            if x1 > x2 or y1 > y2:
                continue
            if width_pred < 10 or height_pred < 50:
                continue
            bbox_gt_augmented.append((x1, y1, x2, y2))

    return bbox_gt_augmented

def evaluate_sampling(image_dim, subregion_dim, bboxes):
    """ Evaluate sampling results 
        Sampled boxes affect the performance of the camera calibration.
        This function gives information about the sampled boxes such as:
        - number of boxes
        - grid coverage of the boxes    
    
    Args:
        image_dim(tuple): image dimensions (width, height)
        subregion_dim(tuple): subregion dimensions (width, height)
        bboxes(list): list of sampled bounding boxes
    
    Returns:
        None
    """
    print('Image dim: ', image_dim)
    print('Grid dim: ', subregion_dim)
    print('Number of bboxes: ', len(bboxes))
    # grid coverage calculation
    has_box = find_empty_regions(image_dim, subregion_dim, bboxes)
    print('has_box: ', has_box)
    grid_coverage = np.sum(has_box) / (has_box.shape[0] * has_box.shape[1]) * 100.0 
    print('Grid coverage(%): ', grid_coverage)

def make_parser():
    parser = argparse.ArgumentParser()
    parser.add_argument('-c', '--config', type=str, default='config.yaml',
                        help='config file')
    parser.add_argument('-i', '--input', type=str, default='bbox.txt',
                        help='input detection bounding box file')
    parser.add_argument('-b', '--background', type=str, default='background.jpg',
                        help='background image')
    parser.add_argument('-o', '--output', type=str, default='output',
                        help='output foler')
    parser.add_argument('-d', '--debug', default=False, action=argparse.BooleanOptionalAction,
                        help='bool for debugging mode')
    return parser

def main():
    """ Main function"""
    parser = make_parser()
    args = parser.parse_args()

    # config 
    config_path = args.config
    input_bbox_path = args.input
    output_path = args.output 
    conf.DEBUG = args.debug

    if not os.path.exists(output_path):
        os.makedirs(output_path)

    # read the first frame from a video file
    img = cv2.imread(args.background) 
    # read bboxes
    df = read_bboxes(input_bbox_path)

    # box sampling method v1 (by hugo)
    # NOTE: this is legacy method. We keep this for now, but it could be 
    # removed in the future. 
    bbox_gt = sample_bbox_v1(config_path, df)
    current_img = draw_bboxes(img, bbox_gt, False)
    fname = os.path.join(output_path, f'bbox_sampling_v1.png')
    cv2.imwrite(fname, current_img)
    
    # save bboxes
    fname = os.path.join(output_path, f'Det_bbox_sampling_v1.txt')
    save_bboxes(bbox_gt, fname)

    # box sampling method v2 (by dyoo)
    bbox_gt_new, bbox_gt_before_grid, bbox_gt_augmented = \
        sample_bboxes_v2(config_path, df, f'{output_path}')
    out_img = draw_bboxes(img, bbox_gt_new, args.debug)
    fname = os.path.join(output_path, f'bbox_sampling_v2.png')
    cv2.imwrite(fname, out_img)
    before_grid_img = draw_bboxes(img, bbox_gt_before_grid, args.debug)
    fname = os.path.join(output_path, f'before_grid_filter.png')
    cv2.imwrite(fname, before_grid_img)

    augment_img = draw_bboxes(img, bbox_gt_augmented, args.debug)
    fname = os.path.join(output_path, f'box_augmentation.png')
    cv2.imwrite(fname, augment_img)

    # save bboxes
    fname = os.path.join(output_path, f'Det_bbox_sampling_v2.txt')
    save_bboxes(bbox_gt_new, fname)

    # save bboxes
    fname = os.path.join(output_path, f'Det_box_augmentation.txt')
    save_bboxes(bbox_gt_augmented, fname)

    # evaluate sampling results
    image_dim = (img.shape[1], img.shape[0])
    bb_cfg = get_config_data(config_path)
    subregion_dim = (bb_cfg.region_split_width, bb_cfg.region_split_height)
    evaluate_sampling(image_dim, subregion_dim, bbox_gt_new)

