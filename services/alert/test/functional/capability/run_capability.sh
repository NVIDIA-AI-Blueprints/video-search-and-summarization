# Capability / load test suite for the event_loop pipeline mode.
#
# Runs the six sustained-stream capability checks against the no-GPU
# functional-test simulators: concurrency exceeding thread count with flat
# consumer lag below the knee (event_loop), the thread-bound contrast
# (thread_bridge), flat per-call VLM latency up to the cap, hard VLM/VST
# concurrency caps under overload, and bounded in-flight with zero message
# loss. Load is generated by incident_stream_publisher.py in --unique mode
# (survivor rate == injection rate); simulated VLM latency comes from the
# threaded NIM stub's NIM_STUB_DELAY_SECONDS.
#
# Usage: ./run_capability.sh [--test TS-001] [--skip-setup]
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FUNCTIONAL_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
P1_ROOT="$FUNCTIONAL_ROOT/p1"
REPO_ROOT="$(cd "$FUNCTIONAL_ROOT/../.." && pwd)"
source "$P1_ROOT/shared/helpers.sh"

export PID_DIR="${PID_DIR:-/tmp/alert_agent_p1_functional}"
ES_HOST="${ES_HOST:-http://127.0.0.1:9200}"
BOOTSTRAP="${BOOTSTRAP:-127.0.0.1:9092}"
TOPIC="${TOPIC:-mdx-incidents}"
BASE_CONFIG="$P1_ROOT/shared/config_base.yaml"
CONSUMER_GROUP="alert-bridge-vlm-group-p1"
KAFKA_CONTAINER="alert-agent-kafka-test"
METRICS_URL="http://127.0.0.1:9081/metrics"
RESULTS_DIR="$PID_DIR/capability_results"
INJECTOR="$SCRIPT_DIR/incident_stream_publisher.py"

ONLY_TEST=""
SKIP_SETUP=0
while [ $# -gt 0 ]; do
    case "$1" in
        --test) ONLY_TEST="$2"; shift 2 ;;
        --skip-setup) SKIP_SETUP=1; shift ;;
        *) echo "Unknown option: $1"; exit 2 ;;
    esac
done

mkdir -p "$PID_DIR" "$RESULTS_DIR"

PASS_COUNT=0
FAIL_COUNT=0
declare -a RESULTS=()

record_result() {
    local name="$1" status="$2" detail="$3"
    RESULTS+=("$status  $name  $detail")
    if [ "$status" = "PASS" ]; then PASS_COUNT=$((PASS_COUNT+1)); else FAIL_COUNT=$((FAIL_COUNT+1)); fi
    print_status "$([ "$status" = "PASS" ] && echo ok || echo fail)" "$name: $status — $detail"
}

# ─── Stack management ────────────────────────────────────────────────────────

ensure_stack() {
    if ! nc -z 127.0.0.1 9092 2>/dev/null; then
        print_status "wait" "Starting Kafka container..."
        docker rm -f "$KAFKA_CONTAINER" 2>/dev/null || true
        docker run -d --name "$KAFKA_CONTAINER" -p 9092:9092 \
            -e KAFKA_BROKER_ID=1 -e KAFKA_PROCESS_ROLES=broker,controller -e KAFKA_NODE_ID=1 \
            -e KAFKA_CONTROLLER_QUORUM_VOTERS=1@localhost:9093 \
            -e KAFKA_CONTROLLER_LISTENER_NAMES=CONTROLLER \
            -e KAFKA_LISTENERS=PLAINTEXT://0.0.0.0:9092,CONTROLLER://0.0.0.0:9093 \
            -e KAFKA_ADVERTISED_LISTENERS=PLAINTEXT://localhost:9092 \
            -e KAFKA_LISTENER_SECURITY_PROTOCOL_MAP=CONTROLLER:PLAINTEXT,PLAINTEXT:PLAINTEXT \
            -e KAFKA_INTER_BROKER_LISTENER_NAME=PLAINTEXT \
            -e KAFKA_OFFSETS_TOPIC_REPLICATION_FACTOR=1 \
            -e CLUSTER_ID=MkU3OEVBNTcwNTJENDM2Qk \
            confluentinc/cp-kafka:7.5.0 >/dev/null
        local waited=0
        while [ $waited -lt 60 ] && ! nc -z 127.0.0.1 9092 2>/dev/null; do sleep 1; waited=$((waited+1)); done
        sleep 5
    fi
    for topic in mdx-incidents mdx-alerts; do
        docker exec "$KAFKA_CONTAINER" kafka-topics --create --bootstrap-server localhost:9092 \
            --topic "$topic" --partitions 1 --replication-factor 1 2>/dev/null || true
    done

    if ! curl -sf http://127.0.0.1:9200/health >/dev/null 2>&1; then
        python3 "$REPO_ROOT/test/sim_scripts/elastic/elastic_sim.py" > "$PID_DIR/elastic_sim.log" 2>&1 &
        echo $! > "$PID_DIR/elastic_sim.pid"
    fi
    if ! curl -sf http://127.0.0.1:30888/status >/dev/null 2>&1; then
        python3 "$REPO_ROOT/test/sim_scripts/vst/vst_sim.py" > "$PID_DIR/vst_sim.log" 2>&1 &
        echo $! > "$PID_DIR/vst_sim.pid"
    fi
    if ! curl -sf http://127.0.0.1:8080/models >/dev/null 2>&1; then
        python3 "$REPO_ROOT/test/sim_scripts/vss/vss_sim.py" > "$PID_DIR/vss_sim.log" 2>&1 &
        echo $! > "$PID_DIR/vss_sim.pid"
    fi
    sleep 2
    start_nim_stub 0
}

start_nim_stub() {
    local delay="$1"
    if [ -f "$PID_DIR/nim_sim.pid" ]; then
        local pid; pid=$(cat "$PID_DIR/nim_sim.pid")
        kill "$pid" 2>/dev/null || true
        sleep 1
        kill -9 "$pid" 2>/dev/null || true
    fi
    NIM_STUB_DELAY_SECONDS="$delay" \
        python3 "$REPO_ROOT/test/sim_scripts/nim/nim_stub_server.py" > "$PID_DIR/nim_sim.log" 2>&1 &
    echo $! > "$PID_DIR/nim_sim.pid"
    sleep 2
}

restart_vst_sim() {
    local delay="$1"
    if [ -f "$PID_DIR/vst_sim.pid" ]; then
        local pid; pid=$(cat "$PID_DIR/vst_sim.pid")
        kill "$pid" 2>/dev/null || true
        sleep 1
        kill -9 "$pid" 2>/dev/null || true
    fi
    VST_SIM_DELAY_SECONDS="$delay" \
        python3 "$REPO_ROOT/test/sim_scripts/vst/vst_sim.py" > "$PID_DIR/vst_sim.log" 2>&1 &
    echo $! > "$PID_DIR/vst_sim.pid"
    sleep 2
}

# ─── Alert Bridge lifecycle (Prometheus enabled) ─────────────────────────────

build_config() {
    # build_config OUT MODE NUM_WORKERS ADW MAX_IN_FLIGHT VLM_CAP VST_CAP [MAX_POLL]
    python3 - "$BASE_CONFIG" "$1" "$2" "$3" "$4" "$5" "$6" "$7" "${8:-50}" <<'PY'
import sys, yaml
src, dst, mode, nw, adw, mif, vlm_cap, vst_cap, max_poll = sys.argv[1:10]
with open(src) as f:
    cfg = yaml.safe_load(f)
aa = cfg.setdefault('alert_agent', {})
aa['pipeline_mode'] = mode
aa['num_workers'] = int(nw)
aa['async_dispatch_workers'] = int(adw)
aa['async_dispatch_max_in_flight'] = int(mif)
aa['include_latency_info'] = True
aio = aa.setdefault('async_io', {})
aio['max_vlm_concurrent'] = int(vlm_cap)
aio['max_vst_concurrent'] = int(vst_cap)
# Sustained-stream ingest must not be poll-starved (empty second topic).
k = cfg.setdefault('kafka', {})
k['poll_timeout'] = 50
k['max_poll_records'] = int(max_poll)
vlm = cfg.setdefault('vlm', {})
vlm['request_timeout'] = 120
with open(dst, 'w') as f:
    yaml.safe_dump(cfg, f, sort_keys=False)
PY
}

stop_ab() {
    stop_alert_bridge_local "$PID_DIR"
    local waited=0
    while [ $waited -lt 10 ] && { nc -z 127.0.0.1 9080 2>/dev/null || nc -z 127.0.0.1 9081 2>/dev/null; }; do
        sleep 1; waited=$((waited+1))
    done
}

start_ab() {
    local config="$1"
    local config_dir; config_dir="$(cd "$(dirname "$config")" && pwd)"
    ALERT_AGENT_CONFIG_DIR="$config_dir" PROMETHEUS_METRICS_ENABLED=true \
        python3 "$REPO_ROOT/enhance_alert_with_vlm.py" --config "$config" > "$PID_DIR/alert_bridge.log" 2>&1 &
    echo $! > "$PID_DIR/alert_bridge.pid"
    local waited=0
    while [ $waited -lt 90 ]; do
        # Readiness now trails the consumer group join, so no settle needed.
        if grep -q "Starting anomaly processing loop" "$PID_DIR/alert_bridge.log" 2>/dev/null; then
            return 0
        fi
        if ! kill -0 "$(cat "$PID_DIR/alert_bridge.pid")" 2>/dev/null; then
            print_status "fail" "Alert Bridge exited during startup"
            tail -5 "$PID_DIR/alert_bridge.log" || true
            return 1
        fi
        sleep 1; waited=$((waited+1))
    done
    print_status "fail" "Alert Bridge did not reach processing loop"
    return 1
}

# ─── Signal helpers ──────────────────────────────────────────────────────────

prom_value() {
    curl -s "$METRICS_URL" 2>/dev/null | awk -v m="$1" '$1==m {v=$2} END{if(v=="")v=0; print v}'
}

group_lag() {
    kafka_consumer_lag "$CONSUMER_GROUP"
}

run_injector() {
    # run_injector RATE DURATION PREFIX [SENSORS]
    python3 "$INJECTOR" --bootstrap "$BOOTSTRAP" --topic "$TOPIC" \
        --num-sensors "${4:-4}" --rate "$1" --duration "$2" \
        --unique --sensor-prefix "$3" > "$RESULTS_DIR/injector_$3.log" 2>&1
}

sample_loop() {
    # sample_loop SECONDS INTERVAL OUTFILE  — rows: epoch,stub_inflight,stub_peak,lag,el_vlm,el_vst,dispatch
    local seconds="$1" interval="$2" out="$3"
    local end=$(( $(date +%s) + seconds ))
    while [ "$(date +%s)" -lt "$end" ]; do
        local stats; stats=$(nim_stub_stats)
        local inflight peak
        inflight=$(echo "$stats" | python3 -c "import sys,json;print(json.load(sys.stdin).get('in_flight',0))" 2>/dev/null || echo 0)
        peak=$(echo "$stats" | python3 -c "import sys,json;print(json.load(sys.stdin).get('peak_in_flight',0))" 2>/dev/null || echo 0)
        echo "$(date +%s),$inflight,$peak,$(group_lag),$(prom_value alert_bridge_event_loop_vlm_in_flight),$(prom_value alert_bridge_event_loop_vst_in_flight),$(prom_value alert_bridge_dispatch_in_flight)" >> "$out"
        sleep "$interval"
    done
}

analyze_samples() {
    # analyze_samples FILE FIELD  → prints "max first_third_avg last_third_avg all_leq(cap)? given CAP via env"
    python3 - "$1" "$2" <<'PY'
import sys
path, field = sys.argv[1], int(sys.argv[2])
rows = []
with open(path) as f:
    for line in f:
        parts = line.strip().split(',')
        if len(parts) > field:
            try:
                rows.append(float(parts[field]))
            except ValueError:
                pass
if not rows:
    print("0 0 0")
    sys.exit(0)
third = max(1, len(rows)//3)
first = sum(rows[:third])/third
last = sum(rows[-third:])/third
print(f"{max(rows):.1f} {first:.1f} {last:.1f}")
PY
}

reset_es() {
    local today; today=$(date -u +%Y-%m-%d)
    curl -sf -X DELETE "$ES_HOST/mdx-vlm-incidents-$today" >/dev/null 2>&1 || true
    curl -sf -X DELETE "$ES_HOST/ab-confirmed-verdicts" >/dev/null 2>&1 || true
}

prepare_run() {
    # prepare_run MODE NW ADW MIF VLM_CAP VST_CAP NIM_DELAY [MAX_POLL]
    local cfg="$PID_DIR/capability_config.yaml"
    stop_ab
    # Committed offsets persist across AB restarts: skip any leftover backlog
    # from a previous (overload) test so each test starts at lag 0.
    docker exec "$KAFKA_CONTAINER" kafka-consumer-groups --bootstrap-server localhost:9092 \
        --group "$CONSUMER_GROUP" --reset-offsets --to-latest --all-topics --execute >/dev/null 2>&1 || true
    start_nim_stub "$7"
    reset_es
    build_config "$cfg" "$1" "$2" "$3" "$4" "$5" "$6" "${8:-50}"
    start_ab "$cfg" || return 1
    # Let the startup VLM warmup request drain before zeroing stub counters,
    # so it cannot leak into the measured concurrency window.
    local waited=0
    while [ $waited -lt 20 ]; do
        local infl; infl=$(nim_stub_stat in_flight)
        [ "${infl:-1}" = "0" ] && break
        sleep 1; waited=$((waited+1))
    done
    nim_stub_reset
    local mode_line
    mode_line=$(grep "Pipeline mode is" "$PID_DIR/alert_bridge.log" | tail -1)
    print_status "info" "AB up — ${mode_line##* is }"
}

# ─── TS-001: event_loop concurrency exceeds thread count; lag flat ──────────
ts_001() {
    echo ""; echo "=== TS-001: concurrency > thread count, lag flat below knee (event_loop) ==="
    prepare_run event_loop 2 2 40 20 20 3 || { record_result TS-001 FAIL "AB startup"; return; }
    local samples="$RESULTS_DIR/ts001_samples.csv"; : > "$samples"
    run_injector 5 150 TS001 &
    local inj=$!
    sample_loop 160 5 "$samples"
    wait $inj || true

    read -r lmax lfirst llast <<< "$(analyze_samples "$samples" 3)"
    read -r gmax _ _ <<< "$(analyze_samples "$samples" 4)"
    local peak; peak=$(nim_stub_stat peak_in_flight)

    # Pipeline-scoped concurrency comes from the AB gauge; the stub peak also
    # counts non-message requests (startup warmup) and is informational.
    local detail="gauge_max=$gmax (workers=2, cap=20) stub_peak=$peak lag first/last=$lfirst/$llast"
    if python3 -c "
import sys
gauge_max, lfirst, llast = float('$gmax'), float('$lfirst'), float('$llast')
sys.exit(0 if (gauge_max > 2 and gauge_max <= 20 and llast <= lfirst + 10) else 1)"; then
        record_result TS-001 PASS "$detail"
    else
        record_result TS-001 FAIL "$detail"
    fi
}

