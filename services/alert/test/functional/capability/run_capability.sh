# ─── TS-003: effective vlm_duration flat as concurrency ramps to cap ────────
ts_003() {
    echo ""; echo "=== TS-003: vlm_duration flat across concurrency ramp (event_loop) ==="
    prepare_run event_loop 2 2 40 10 20 2 || { record_result TS-003 FAIL "AB startup"; return; }
    local means=()
    for rate in 1 3 5; do
        local s0 c0 s1 c1
        s0=$(prom_value alert_bridge_vlm_duration_seconds_sum)
        c0=$(prom_value alert_bridge_vlm_duration_seconds_count)
        run_injector "$rate" 60 "TS003R$rate"
        sleep 8   # let in-flight calls finish observing
        s1=$(prom_value alert_bridge_vlm_duration_seconds_sum)
        c1=$(prom_value alert_bridge_vlm_duration_seconds_count)
        means+=("$(python3 -c "s=$s1-$s0;c=$c1-$c0;print(f'{s/c:.3f}' if c>0 else '0')")")
    done
    local base="${means[0]}"
    local detail="mean@1/s=${means[0]} @3/s=${means[1]} @5/s=${means[2]} (stub=2s)"
    if python3 -c "
import sys
base, m2, m3 = float('${means[0]}'), float('${means[1]}'), float('${means[2]}')
ok = base > 0 and m2 <= base*1.2 and m3 <= base*1.2
sys.exit(0 if ok else 1)"; then
        record_result TS-003 PASS "$detail"
    else
        record_result TS-003 FAIL "$detail"
    fi
}

# ─── TS-004: VLM cap never exceeded under overload ───────────────────────────
ts_004() {
    echo ""; echo "=== TS-004: VLM cap never exceeded under overload (event_loop) ==="
    prepare_run event_loop 2 2 40 5 20 3 || { record_result TS-004 FAIL "AB startup"; return; }
    local samples="$RESULTS_DIR/ts004_samples.csv"; : > "$samples"
    run_injector 10 180 TS004 &
    local inj=$!
    sample_loop 190 1 "$samples"
    wait $inj || true

    # Zero-tolerance check on the pipeline gauge (EVENT_LOOP_VLM_IN_FLIGHT per
    # spec); the stub count also sees transport-level artifacts (SDK retries,
    # startup warmup) and is diagnostic only.
    local violations gauge_max
    read -r violations gauge_max <<< "$(python3 - "$samples" <<'PY'
import sys
count = 0
gmax = 0.0
with open(sys.argv[1]) as f:
    for line in f:
        parts = line.strip().split(',')
        if len(parts) > 4:
            try:
                v = float(parts[4])
            except ValueError:
                continue
            gmax = max(gmax, v)
            if v > 5:
                count += 1
print(count, gmax)
PY
)"
    local peak; peak=$(nim_stub_stat peak_in_flight)
    local detail="gauge_max=$gauge_max cap=5 gauge_samples_over_cap=$violations stub_peak=$peak"
    if python3 -c "import sys; sys.exit(0 if int('$violations')==0 and float('$gauge_max')==5.0 else 1)"; then
        record_result TS-004 PASS "$detail"
    else
        record_result TS-004 FAIL "$detail"
    fi
}

