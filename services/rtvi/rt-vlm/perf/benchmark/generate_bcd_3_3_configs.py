"""Render BCD 3.3 platform seed configs from the existing BCD workload."""

import re
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE = HERE / "rtvi_vlm_bcd_3_2_config.yaml"
PROFILES = {
    # platform: (model preset, max-live starting count, increment, concurrency sweep)
    "rtx_pro_6000_se": ("cr3-super-reasoner-nvfp4", 1, 5, [1, 16, 32, 64, 128]),
    "rtx_pro_4500": ("cr3-super-reasoner-nvfp4", 1, 1, [1, 4, 8, 16, 32]),
    "l40s": ("cr3-nano-reasoner-fp8", 1, 5, [1, 16, 32, 64, 128]),
    "h100_sxm": ("cr3-super-reasoner-fp8", 1, 5, [1, 16, 32, 64, 128]),
    "b200_sxm": ("cr3-super-reasoner-nvfp4", 1, 5, [1, 16, 32, 64, 128]),
    "agx_thor_t5000": ("cr3-nano-reasoner-nvfp4", 1, 1, [1, 4, 8, 16]),
    "dgx_spark": ("cr3-nano-reasoner-nvfp4", 1, 1, [1, 4, 8, 16]),
    "agx_orin": ("cosmos3-edge-bf16", 1, 1, [1, 2, 4, 8]),
    "gb200": ("cr3-nano-reasoner-nvfp4", 1, 5, [1, 16, 32, 64, 128]),
}


def render(
    source: str, platform: str, preset: str, initial: int, step: int, levels: list[int]
) -> str:
    assert source.count("initial_stream_count: 5") == 6
    assert source.count("add_stream_count: 5") == 6
    assert source.count("stream_count: [1, 16, 32, 64, 128]") == 6
    assert source.count("concurrency_levels: [1, 16, 32, 64, 128]") == 6
    display = platform.replace("_", " ").upper()
    header = (
        "# Generated by generate_bcd_3_3_configs.py; edit PROFILES, then regenerate.\n"
        f"# Platform: {display}; initial search seeds only, not validated capacity.\n"
        f"# Runtime model: {preset}; setup_perf_env.sh reads global.model_preset.\n"
    )
    if platform == "agx_orin":
        header += "# Cosmos3-Edge BF16 needs Orin preflight before the suite.\n"
    else:
        header += "# Verify exact model access and platform runtime before the suite.\n"
    text = source.replace(
        "# RTVI VLM BCD 3.2 benchmark configuration.\n",
        "# RTVI VLM BCD 3.3 benchmark configuration.\n" + header,
    )
    text = text.replace("BCD_VSS_3-2", "BCD_VSS_3-3").replace("BCD 3.2", "BCD 3.3")
    text = text.replace("dGPU stream counts", f"{display} stream counts")
    text = text.replace(
        "#   - Non-streaming video request concurrency: [1, 16, 32, 64, 128]\n"
        "#     Use --concurrency-levels 1 8 16 for AGX Thor and DGX Spark edge runs.\n",
        f"#   - Platform concurrency seed: {levels}; benchmark failures remain failures.\n",
    )
    text = text.replace(
        'output_dir: "rtvi-vlm-bcd-3-2-report"',
        f'output_dir: "rtvi-vlm-bcd-3-3-{platform}-report"',
    )
    text = text.replace("global:\n", f'global:\n  model_preset: "{preset}"\n', 1)
    text = re.sub(r'rtvi_backend: "[^"]+"', 'rtvi_backend: "http://localhost:8010/v1"', text)
    text = re.sub(r'dcgm_exporter_url: "[^"]+"', 'dcgm_exporter_url: "http://localhost:9400/metrics"', text)
    text = re.sub(r'node_exporter_url: "[^"]+"', 'node_exporter_url: "http://localhost:9100/metrics"', text)
    text = text.replace("initial_stream_count: 5", f"initial_stream_count: {initial}")
    text = text.replace(
        "add_stream_count: 5\n",
        f"add_stream_count: {step}\n"
        f"        latency_plateau_counts: {levels}\n"
        "        latency_plateau_duration_seconds: 300\n",
    )
    text = text.replace("stream_count: [1, 16, 32, 64, 128]", f"stream_count: {levels}")
    text = text.replace("concurrency_levels: [1, 16, 32, 64, 128]", f"concurrency_levels: {levels}")
    if platform == "agx_orin":
        # Cosmos3-Edge: (640 / 16 / 2)^2 = 400 vision tokens per frame.
        frames = {"10": "5", "20": "10", "40": "20"}
        text = re.sub(
            r"(num_frames_per_second_or_fixed_frames_chunk: )(10|20|40)\b",
            lambda match: match[1] + frames[match[2]],
            text,
        )
        text = re.sub(
            r"(10|20|40) frames \(~([248])K\)",
            lambda match: frames[match[1]] + f" frames (~{match[2]}K)",
            text,
        )
        text = text.replace(
            "Frame counts per chunk: 10, 20, 40,",
            "Frame counts per chunk: 5, 10, 20,",
        )
    return text


def main() -> None:
    source = SOURCE.read_text()
    for platform, (preset, initial, step, levels) in PROFILES.items():
        output = HERE / f"rtvi_vlm_bcd_3_3_{platform}_config.yaml"
        output.write_text(render(source, platform, preset, initial, step, levels))
        print(output.name)


if __name__ == "__main__":
    main()
